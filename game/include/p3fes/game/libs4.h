// Phase 5 slice libs4: CRI middleware, third pass (game/src/cri/libs4_{svm,rofs,rsu,sofdec}.cpp).
//   * SVM, the rest of it: the server table (8 types x 6 slots, register / set / delete / execute), the execution
//     counters, init / finish, the callback setters, the test-and-set;
//   * ROFS's pure parts: the file handle (fill, create, reopen, seek, tell, status, transfer counts), the volume record,
//     the error reporter and last error, the work-area flags, the ISO 9660 record copiers, the CVM header parsers (CVMH,
//     CVMF, ZONE), the PFS lock / wait helpers, ROCI's interface getters;
//   * RSU, the CVM descrambler: the three prime hashes, the fixed keys, the sector round keys, the nine permutation
//     rounds, the decipher entry points;
//   * the glue next to Sofdec: CFT's work pointer and its 8-bit to 32-bit converter, the newlib lock stubs, the
//     callback thunks of 0x7B292C, the reader methods of 0x56F888-0x56FEC0.
// Every body is register-ABI (arguments in $a0.., the result in $v0), generated by p3fes_handgen and made readable
// without changing a statement (docs/PHASE5_AGENT_BRIEF.md). Bracketed names are proposals: the binary's own where its
// strings name the function (SVM's error texts, ROFS's "../../rofs_hn.c" texts, the version texts), our own elsewhere
// (ADR-0009; not imported). No CRI SDK material was used.
