// --- h_resrcman: the resource-manager thread ---------------------------------------------------------------------
// One worker thread (H_Resman_ThreadProc, priority 28, its 128 KiB stack at 0x803640) serves a list of requests (the
// worker's {head, tail} at 0x7E5860; the 256 request records of 476 bytes at 0x7E5A40); the per-frame pump
// H_ResrcMan_Update issues the request's H_Cdvd load and, when the file is in, hands the request to the thread through
// the 8-byte control block at $gp-0x4DC0 ({u16 go, u32 req}) and wakes it. Requests: +0 next, +164 the file name (empty = no file), +420 state (0 new, 1 loading, 2 with the
// thread, 3 done), +424 the H_Cdvd archive flag, +428 the kind (0..9: which RenderWare loader the thread runs), +432 the
// H_Cdvd node, +464 u16 frames spent with the thread; the loaders' results land at +12 / +16 / +20 / +24 / +28 /
// +436 / +440 / +452 / +460 / +468.
namespace resman {
inline constexpr s32 kGpStarted = -19916;   // 0x7CDF24: 1 once H_ResrcMan_Init made the thread
inline constexpr s32 kGpThreadId = -19912;  // 0x7CDF28: the worker's thread id
inline constexpr s32 kGpControl = -19904;   // 0x7CDF30: {u16 go, u32 request} handed to the worker
inline constexpr u32 kRequestList = 0x7E5860u;
inline constexpr s32 kNext = 0;
inline constexpr s32 kFileName = 164;
inline constexpr s32 kState = 420;
inline constexpr s32 kArchive = 424;
inline constexpr s32 kKind = 428;
inline constexpr s32 kNode = 432;
inline constexpr s32 kFramesWaited = 464;
}  // namespace resman

