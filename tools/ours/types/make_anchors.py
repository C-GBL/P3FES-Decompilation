"""Write the p3fes_types anchor file from seeds.json (the header-known records and where their pointers arrive).

    python -I tools/ours/types/make_anchors.py [--seeds tools/ours/types/seeds.json] --out <anchors.txt>

One line per anchor: `<RecordName> param|ret|gslot|gobj <hex addr> [arg index]`. Every anchor of one record pins the
same name, so the solver keeps two different records apart (an anchor clash vetoes a merge).
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def load_seeds(path):
    """seeds.json plus every tools/ours/types/deltas/*.json (same format; one file per slice, so parallel slices never
    edit one shared file). A delta record with an existing name adds its anchors and fields (a field at an offset the
    seeds already have replaces it: the slice confirmed or corrected it); a new name adds a record."""
    with open(path, encoding="utf-8") as f:
        seeds = json.load(f)
    recs = {r["name"]: r for r in seeds["records"]}
    ddir = os.path.join(os.path.dirname(os.path.abspath(path)), "deltas")
    if os.path.isdir(ddir):
        for fn in sorted(os.listdir(ddir)):
            if not fn.endswith(".json"):
                continue
            with open(os.path.join(ddir, fn), encoding="utf-8") as f:
                delta = json.load(f)
            for r in delta.get("records", []):
                r.setdefault("note", "delta " + fn)
                base = recs.get(r["name"])
                if base is None:
                    r.setdefault("anchors", [])
                    r.setdefault("fields", [])
                    r.setdefault("size", None)
                    r.setdefault("header", "tools/ours/types/deltas/" + fn)
                    r.setdefault("line", 1)
                    seeds["records"].append(r)
                    recs[r["name"]] = r
                    continue
                have = {(a["how"], a.get("fn"), a.get("addr"), a.get("index", 0)) for a in base["anchors"]}
                for a in r.get("anchors", []):
                    if (a["how"], a.get("fn"), a.get("addr"), a.get("index", 0)) not in have:
                        base["anchors"].append(a)
                byoff = {f["off"]: f for f in base["fields"]}
                for fl in r.get("fields", []):
                    byoff[fl["off"]] = fl
                base["fields"] = [byoff[o] for o in sorted(byoff)]
                if r.get("size"):
                    base["size"] = r["size"]
    return seeds


def anchor_lines(seeds):
    out = []
    for rec in seeds["records"]:
        for a in rec.get("anchors", []):
            how = a["how"]
            if how in ("param", "ret"):
                addr = int(a["fn"], 16)
                idx = int(a.get("index", 0))
                out.append(f"{rec['name']} {how} {addr:X} {idx}" if how == "param" else f"{rec['name']} ret {addr:X}")
            elif how in ("gslot", "gobj"):
                out.append(f"{rec['name']} {how} {int(a['addr'], 16):X}")
        if rec.get("size") and rec.get("anchors"):
            out.append(f"size {rec['name']} {int(rec['size'])}")
    return out


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", default=os.path.join(HERE, "seeds.json"))
    ap.add_argument("--out", required=True)
    args = ap.parse_args(argv)
    seeds = load_seeds(args.seeds)
    lines = anchor_lines(seeds)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("# generated by tools/ours/types/make_anchors.py from seeds.json\n")
        f.write("\n".join(lines) + "\n")
    print(f"{len(lines)} anchor and size lines for {len(seeds['records'])} records -> {args.out}")


if __name__ == "__main__":
    main(sys.argv[1:])
